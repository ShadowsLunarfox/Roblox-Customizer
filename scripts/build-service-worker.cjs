const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const output = path.join(root, 'src/background/service-worker-bundle.js');
const sources = [
  'src/shared/routes.js',
  'src/background/page-context.js',
  'src/assets/vendor/fzstd-0.1.1.js',
  'src/assets/model-reader.js',
  'src/assets/asset-core.js',
  'src/background/asset-tools-background.js',
  'src/background/animation-preview-background.js',
  'src/currency/robux-currency-core.js',
  'src/background/robux-currency-background.js',
  'src/home/pinned-games-core.js',
  'src/background/pinned-games-background.js',
  'src/home/pinned-friends-core.js',
  'src/background/pinned-friends-background.js',
  'src/background/friends-manager-background.js',
  'src/notes/game-notes-core.js',
  'src/background/game-notes-background.js',
  'src/servers/server-history-core.js',
  'src/playtime/playtime-core.js',
  'src/background/playtime-background.js',
  'src/background/server-history-background.js',
  'src/settings/backup-core.js',
  'src/background/backup-background.js',
  'src/background/service-worker.js'
];

function build() {
  const sections = sources.map((file, index) => {
    let source = fs.readFileSync(path.join(root, file), 'utf8').replace(/\r\n/g, '\n');
    if (index === sources.length - 1) {
      const loader = /^if \(typeof importScripts === 'function'\) \{\n[\s\S]*?\n\}\n\n/;
      if (!loader.test(source)) throw new Error('Service worker import list changed; update the bundle sources.');
      source = source.replace(loader, '');
    }
    return `// ${file}\n${source.trimEnd()}\n;`;
  });
  return '// Generated by node scripts/build-service-worker.cjs. Do not edit directly.\n'
    + sections.join('\n\n') + '\n';
}

if (require.main === module) {
  const built = build();
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== built) {
      console.error('Service worker bundle is out of date. Run node scripts/build-service-worker.cjs.');
      process.exitCode = 1;
    }
  } else {
    fs.writeFileSync(output, built);
  }
}

module.exports = { build };
