const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const output = path.join(root, 'src/shared/page-bridge-bundle.js');
const sources = ['src/shared/routes.js', 'src/shared/compatibility.js',
  'src/shared/server-card-view.js', 'src/shared/friend-actions.js', 'src/shared/friends-native-view.js', 'src/shared/page-bridge.js'];

function build() {
  return '// Generated by node scripts/build-page-bridge.cjs. Do not edit directly.\n'
    + sources.map(file => `// ${file}\n${fs.readFileSync(path.join(root, file), 'utf8')
      .replace(/\r\n/g, '\n').trimEnd()}\n;`).join('\n\n') + '\n';
}

if (require.main === module) {
  const built = build();
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== built) {
      console.error('Page bridge bundle is out of date. Run node scripts/build-page-bridge.cjs.');
      process.exitCode = 1;
    }
  } else fs.writeFileSync(output, built);
}

module.exports = { build };
