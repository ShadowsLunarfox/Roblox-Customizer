// Extract property categories and enum names from Roblox's published Studio API data.
const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const workspace=path.resolve(__dirname,'..');
async function build(input){
  let source;
  if(input)source=JSON.parse(fs.readFileSync(input,'utf8'));
  else{
    const versionResponse=await fetch('https://clientsettingscdn.roblox.com/v2/client-version/WindowsStudio64');
    if(!versionResponse.ok)throw Error('Studio version request failed');const version=await versionResponse.json();
    if(!/^version-[a-f0-9]+$/.test(version.clientVersionUpload))throw Error('Invalid Studio version');
    const url=`https://setup.rbxcdn.com/${version.clientVersionUpload}-API-Dump.json`,response=await fetch(url);if(!response.ok)throw Error('API data request failed');
    source={version:version.clientVersionUpload,url,data:await response.json()};
  }
  const classes={},enums={};
  for(const c of source.data.Classes){const properties={};for(const member of c.Members)if(member.MemberType==='Property')properties[member.Name]=[member.Category||'Data',member.ValueType?.Category==='Enum'?member.ValueType.Name:''];classes[c.Name]=[c.Superclass,properties];}
  for(const e of source.data.Enums)enums[e.Name]=Object.fromEntries(e.Items.map(i=>[i.Value,i.Name]));
  const data=JSON.stringify({classes,enums}),hash=crypto.createHash('sha256').update(data).digest('hex');
  const script=`/* Generated by scripts/build-model-schema.cjs. Reference data, not executable asset content.
   Roblox Studio ${source.version}; ${source.url}
   Extracted data SHA-256: ${hash} */
(function(root){'use strict';if(root.RobloxCustomizerModelSchema)return;
const data=${data};
function property(className,name){for(let n=0;n<100&&Object.hasOwn(data.classes,className);n++){const c=data.classes[className];if(Object.hasOwn(c[1],name))return c[1][name];className=c[0];}return null;}
function enumName(className,name,value){const type=property(className,name)?.[1],items=type&&Object.hasOwn(data.enums,type)?data.enums[type]:null;return items&&Object.hasOwn(items,value)?items[value]:null;}
const api=Object.freeze({property,enumName,version:${JSON.stringify(source.version)}});root.RobloxCustomizerModelSchema=api;if(typeof module==='object'&&module.exports)module.exports=api;})(globalThis);
`;
  fs.writeFileSync(path.join(workspace,'src/assets/model-schema.js'),script);return {classes:Object.keys(classes).length,enums:Object.keys(enums).length,bytes:Buffer.byteLength(script)};
}
if(require.main===module)build(process.argv[2]).then(result=>console.log(result)).catch(error=>{console.error(error.message);process.exitCode=1});
module.exports={build};
