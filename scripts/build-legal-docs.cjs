// The packaged policy page and public Markdown use the same reviewed content.
const fs = require('node:fs');
const path = require('node:path');
const workspace = path.resolve(__dirname, '..');

function filename(type, language) {
  return `${type.toUpperCase()}${language === 'en' ? '' : '.' + language}.md`;
}

function build() {
  const data = JSON.parse(fs.readFileSync(path.join(workspace, 'src/legal/content.json'), 'utf8'));
  const documents = {};
  for (const [language, locale] of Object.entries(data.locales)) {
    for (const type of ['privacy', 'terms']) {
      const policy = locale[type];
      const links = Object.entries(data.locales).map(([code, translation]) =>
        code === language ? translation.name : `[${translation.name}](${filename(type, code)})`).join(' · ');
      const other = type === 'privacy' ? 'terms' : 'privacy';
      const lines = [
        `<!-- Generated by scripts/build-legal-docs.cjs; edit src/legal/content.json. -->`,
        `# Roblox Customizer — ${policy.title}`, '', links, '',
        `${locale.updatedLabel}: ${data.updated}<br>`,
        `${locale.publisherLabel}: ${data.publisher}`, '', policy.intro, '',
        `[${locale[other].title}](${filename(other, language)})`, ''
      ];
      for (const section of policy.sections) {
        lines.push(`## ${section.heading}`, '');
        for (const paragraph of section.paragraphs || []) lines.push(paragraph, '');
        if (section.items) lines.push(...section.items.map(text => `- ${text}`), '');
      }
      lines.push(`## ${locale.contactHeading}`, '', locale.contactText, '',
        `[${data.email}](mailto:${data.email}) · ${data.contacts.map(contact => `[${contact.label}](${contact.url})`).join(' · ')}`, '');
      documents[filename(type, language)] = lines.join('\n');
    }
  }
  return documents;
}

if (require.main === module) {
  for (const [file, content] of Object.entries(build())) fs.writeFileSync(path.join(workspace, file), content, 'utf8');
  process.stdout.write('Updated Terms of Service and Privacy Policy in all three languages.\n');
}
module.exports = { build };
